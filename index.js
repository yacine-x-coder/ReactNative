/* =========================================================
   QUIZ
========================================================= */

function createQuiz(lesson) {

  const allTitles =
    lessons.map(item =>
      getText(item.title)
    );

  const correct =
    getText(lesson.title);

  const alternatives =
    allTitles
      .filter(title => title !== correct)
      .slice(
        Math.max(0, lesson.id - 1),
        Math.max(0, lesson.id - 1) + 2
      );

  while (alternatives.length < 2) {
    alternatives.push(
      state.language === "ar"
        ? "مفهوم آخر"
        : state.language === "fr"
          ? "Autre concept"
          : "Another concept"
    );
  }

  const options = [
    correct,
    ...alternatives
  ].sort(() => Math.random() - 0.5);

  return `

    <div class="quiz">

      <div class="quiz-question">

        ${t("quiz")}:
        ${
          state.language === "ar"
            ? `أي مفهوم يشرحه هذا الدرس؟`
            : state.language === "fr"
              ? `Quel concept cette leçon explique-t-elle ?`
              : `Which concept does this lesson explain?`
        }

      </div>

      <div>

        ${options.map(option => `

          <button
            class="quiz-option"
            data-answer="${
              encodeURIComponent(option)
            }"
            data-correct="${
              option === correct
            }"
          >
            ${escapeHTML(option)}
          </button>

        `).join("")}

      </div>

    </div>

  `;
}


