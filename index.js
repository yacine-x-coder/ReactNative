/* =========================================================
   LESSON LIST
========================================================= */

function updateLessonList() {

  const search =
    state.search.toLowerCase().trim();

  const filtered =
    lessons.filter(lesson => {

      const matchesFilter =
        state.filter === "all" ||
        lesson.difficulty === state.filter;

      const title =
        getText(lesson.title)
          .toLowerCase();

      const matchesSearch =
        !search ||
        title.includes(search) ||
        lesson.key.includes(search);

      return (
        matchesFilter &&
        matchesSearch
      );

    });


  if (!filtered.length) {

    $("#lessonList").innerHTML = `
      <div style="
        padding:20px;
        text-align:center;
        color:var(--muted);
        font-size:12px;
      ">
        ${t("noResults")}
      </div>
    `;

    return;
  }


  let html = "";

  let currentModule =
    null;


  filtered.forEach(lesson => {

    if (
      lesson.module !==
      currentModule
    ) {

      currentModule =
        lesson.module;

      html += `

        <div class="module-heading">
          ${escapeHTML(
            getModuleTitle(
              lesson.module
            )
          )}
        </div>

      `;

    }


    const completed =
      state.completed.has(
        lesson.id
      );

    const active =
      lessons[state.currentLesson]?.id ===
      lesson.id;


    html += `

      <button
        class="
          lesson-item
          ${active ? "active" : ""}
          ${completed ? "completed" : ""}
        "
        data-lesson-id="${lesson.id}"
      >

        <span class="lesson-number">
          ${completed ? "✓" : lesson.id}
        </span>

        <span class="lesson-item-title">
          ${escapeHTML(
            getText(lesson.title)
          )}
        </span>

      </button>

    `;

  });


  $("#lessonList").innerHTML =
    html;


  $$(".lesson-item").forEach(
    button => {

      button.addEventListener(
        "click",
        () => {

          const id =
            Number(
              button.dataset.lessonId
            );

          const index =
            lessons.findIndex(
              lesson =>
                lesson.id === id
            );

          renderLesson(index);

          if (
            window.innerWidth <= 900
          ) {
            closeSidebar();
          }

        }
      );

    }
  );

}


