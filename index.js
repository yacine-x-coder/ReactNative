    lesson.duration;

  $("#lessonTitle").textContent =
    getText(lesson.title);

  $("#lessonDescription").textContent =
    getText(lesson.description);

  $("#lessonArticle").innerHTML =
    renderLessonArticle(lesson);

  $("#breadcrumbCurrent").textContent =
    getText(lesson.title);


  renderToc();

  updateCompleteButton();

  updateNavigation();

  updateLessonList();

  window.scrollTo({
    top: 0,
    behavior:
      state.animation === "off"
        ? "auto"
        : "smooth"
  });

  attachLessonEvents();
